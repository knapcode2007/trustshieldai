"""
TrustShield AI - Machine Learning Prediction Service
FastAPI-compatible inference service.
Adheres to strict verification integrity:
Never presents untrained heuristics as a trained ML model.
Marks inference 'unavailable' when no validated model artifact is loaded.
Validates SHA-256 integrity hashes, feature schemas, and runtime compatibility before deserializing.
Provides defensible local feature attribution without conflating raw values with global weights.
"""

import hashlib
import hmac
import json
import logging
import os
import sys
from typing import Any, Dict, List, Optional, Tuple
from backend.app.ml.features import URLFeatureExtractor

logger = logging.getLogger("trustshield.ml.service")


class PhishingMLService:
    """Manages model artifact lifecycle, feature extraction, and real ML inference."""

    def __init__(self, model_name: str = "TrustShield-RandomForest-PhishLex-v1.0"):
        self.model_name = model_name
        self.model_version = model_name
        self.is_trained: bool = False
        self.status: str = "unavailable"
        self.model_instance = None
        self.metadata: Dict[str, Any] = {}
        self.load_error: Optional[str] = None
        self.models_dir = os.path.join(os.path.dirname(__file__), "models")

        # Attempt to load and validate model artifact if present on disk
        self._load_artifact()

    def _compute_file_sha256(self, filepath: str) -> str:
        """Computes the SHA-256 hexadecimal digest of a file in 64KB chunks."""
        hasher = hashlib.sha256()
        with open(filepath, "rb") as f:
            while chunk := f.read(65536):
                hasher.update(chunk)
        return hasher.hexdigest().lower()

    def _load_artifact(self) -> None:
        """
        Inspects disk for validated model artifact and loads serialized estimator safely.
        Validates:
        1. Manifest and binary file coexistence.
        2. Manifest schema, model_version, and feature schema conformity.
        3. Runtime Python version compatibility.
        4. SHA-256 cryptographic digest verification before invoking joblib.load().

        SECURITY NOTE:
        SHA-256 verification provides an integrity guardrail against file corruption
        or mismatched manifest/artifact pairings. Checksums are NOT proof that an
        untrusted pickle is safe from arbitrary code execution. Serialized artifacts
        must only be generated by trusted, sanctioned build/training pipelines.
        """
        self.is_trained = False
        self.status = "unavailable"
        self.model_instance = None
        self.load_error = None

        json_manifest = os.path.join(self.models_dir, "trustshield_rf_v1.json")
        joblib_artifact = os.path.join(self.models_dir, "trustshield_rf_v1.joblib")

        # Check for artifact presence
        has_manifest = os.path.exists(json_manifest)
        has_joblib = os.path.exists(joblib_artifact)

        if not has_manifest and not has_joblib:
            self.load_error = "No model artifact files found on disk."
            return

        if not has_manifest:
            self.load_error = "Model binary exists on disk, but artifact manifest JSON is missing."
            logger.warning("[ML Service] Artifact load aborted: missing manifest %s", json_manifest)
            return

        if not has_joblib:
            self.load_error = "Model manifest exists on disk, but serialized estimator binary is missing."
            logger.warning("[ML Service] Artifact load aborted: missing binary %s", joblib_artifact)
            return

        # 1. Parse and validate JSON manifest
        try:
            with open(json_manifest, "r", encoding="utf-8") as f:
                self.metadata = json.load(f)
        except Exception as e:
            self.load_error = f"Failed to parse model manifest JSON: {str(e)}"
            logger.error("[ML Service] %s", self.load_error)
            return

        self.model_version = self.metadata.get("model_version", self.model_name)

        # 2. Validate feature schema and count
        manifest_features = self.metadata.get("feature_names")
        expected_features = URLFeatureExtractor.FEATURE_NAMES

        if not isinstance(manifest_features, list):
            self.load_error = "Model manifest lacks a valid 'feature_names' array."
            logger.error("[ML Service] %s", self.load_error)
            return

        if len(manifest_features) != len(expected_features):
            self.load_error = (
                f"Feature count mismatch: Manifest contains {len(manifest_features)} features, "
                f"but feature extractor expects {len(expected_features)}."
            )
            logger.error("[ML Service] %s", self.load_error)
            return

        if manifest_features != expected_features:
            self.load_error = "Feature names or order in manifest do not match extractor schema exactly."
            logger.error("[ML Service] %s", self.load_error)
            return

        # 3. Validate runtime compatibility (if recorded in manifest)
        runtime_meta = self.metadata.get("runtime", {})
        if isinstance(runtime_meta, dict):
            recorded_py = runtime_meta.get("python_version")
            if recorded_py:
                try:
                    recorded_major = int(recorded_py.split(".")[0])
                    current_major = sys.version_info[0]
                    if recorded_major != current_major:
                        self.load_error = (
                            f"Incompatible Python runtime: Artifact was compiled on Python {recorded_py}, "
                            f"running on Python {sys.version.split()[0]}."
                        )
                        logger.error("[ML Service] %s", self.load_error)
                        return
                except Exception:
                    pass

        # 4. SHA-256 integrity check BEFORE deserialization
        expected_hash = self.metadata.get("artifact_sha256") or self.metadata.get("sha256")
        if not expected_hash or not isinstance(expected_hash, str) or len(expected_hash.strip()) < 32:
            self.load_error = (
                "Manifest is missing a valid 'artifact_sha256' integrity digest. "
                "Refusing to load untracked serialized binary."
            )
            logger.error("[ML Service] %s", self.load_error)
            return

        try:
            actual_hash = self._compute_file_sha256(joblib_artifact)
        except Exception as e:
            self.load_error = f"Failed to compute SHA-256 digest of artifact binary: {str(e)}"
            logger.error("[ML Service] %s", self.load_error)
            return

        if not hmac.compare_digest(actual_hash.lower(), expected_hash.strip().lower()):
            self.load_error = (
                f"Artifact integrity verification failed: SHA-256 mismatch "
                f"(expected {expected_hash[:16]}..., actual {actual_hash[:16]}...)."
            )
            logger.error("[ML Service] %s", self.load_error)
            return

        # 5. Load serialized estimator
        try:
            import joblib
            loaded = joblib.load(joblib_artifact)

            if not hasattr(loaded, "predict_proba"):
                self.load_error = "Loaded model estimator does not implement 'predict_proba'."
                logger.error("[ML Service] %s", self.load_error)
                return

            self.model_instance = loaded
            self.is_trained = True
            self.status = "operational"
            self.load_error = None
            logger.info("[ML Service] Model '%s' successfully validated and loaded.", self.model_version)
        except Exception as e:
            self.is_trained = False
            self.status = "unavailable"
            self.model_instance = None
            self.load_error = f"Model deserialization failed: {str(e)}"
            logger.error("[ML Service] %s", self.load_error)

    @classmethod
    def compute_local_evidence(
        cls,
        extracted: Dict[str, Any],
        vector: List[float],
        global_importances: Dict[str, float],
    ) -> Tuple[Dict[str, float], List[Dict[str, Any]]]:
        """
        Computes defensible local feature attribution for a specific URL.
        DOES NOT multiply raw unscaled values by global feature importance.
        Instead:
        1. Normalizes each individual risk factor into a bounded signal intensity s_j in [0.0, 1.0].
        2. Combines active risk signal intensity with the model's global feature weight.
        3. Returns clearly separated local risk factors and evidence details.
        """
        feature_names = URLFeatureExtractor.FEATURE_NAMES
        contributing: Dict[str, float] = {}
        evidence_details: List[Dict[str, Any]] = []

        val_map = {name: val for name, val in zip(feature_names, vector)}

        def _evaluate_feature(
            fname: str,
            signal_intensity: float,
            description: str,
        ):
            if signal_intensity <= 0.0:
                return
            bounded_signal = min(1.0, max(0.0, signal_intensity))
            weight = global_importances.get(fname, 0.03)
            local_impact = round(bounded_signal * weight, 4)
            if local_impact > 0.001:
                contributing[fname] = local_impact
                evidence_details.append({
                    "feature": fname,
                    "raw_value": val_map.get(fname, 0.0),
                    "signal_intensity": round(bounded_signal, 4),
                    "global_importance": round(weight, 4),
                    "local_impact": local_impact,
                    "description": description,
                })

        # Binary high-confidence indicators
        if val_map.get("has_ip_literal", 0.0) >= 1.0:
            _evaluate_feature("has_ip_literal", 1.0, "Host is a raw numerical IP literal instead of a domain name")
        if val_map.get("is_punycode", 0.0) >= 1.0:
            _evaluate_feature("is_punycode", 1.0, "Domain uses Punycode (IDN) homograph obfuscation prefix 'xn--'")
        if val_map.get("brand_squatting_detected", 0.0) >= 1.0:
            squatted = extracted.get("squatted_brands", [])
            _evaluate_feature("brand_squatting_detected", 1.0, f"Unauthorized brand impersonation detected ({', '.join(squatted)})")
        if val_map.get("brand_in_subdomain", 0.0) >= 1.0:
            _evaluate_feature("brand_in_subdomain", 1.0, "Brand token embedded in subdomain of third-party domain")
        if val_map.get("is_high_risk_tld", 0.0) >= 1.0:
            _evaluate_feature("is_high_risk_tld", 1.0, "Domain uses an abuse-prone top-level domain (TLD)")
        if val_map.get("consecutive_hyphens", 0.0) >= 1.0:
            _evaluate_feature("consecutive_hyphens", 0.8, "Contains consecutive hyphens ('--') indicative of domain spoofing")
        if val_map.get("has_hex_pattern", 0.0) >= 1.0:
            _evaluate_feature("has_hex_pattern", 0.8, "URL contains 16+ hex characters characteristic of payload tracking")
        if val_map.get("count_at", 0.0) >= 1.0:
            _evaluate_feature("count_at", 1.0, "URL contains '@' credential delimiter (URL userinfo obfuscation)")
        if val_map.get("is_https", 1.0) == 0.0:
            _evaluate_feature("is_https", 0.7, "Unencrypted plaintext HTTP protocol")

        # Suspicious keyword signals
        auth_k = val_map.get("auth_keyword_count", 0.0)
        if auth_k > 0:
            _evaluate_feature("auth_keyword_count", min(1.0, auth_k / 2.0), f"Authentication credential keywords present ({int(auth_k)})")

        sec_k = val_map.get("security_keyword_count", 0.0)
        if sec_k > 0:
            _evaluate_feature("security_keyword_count", min(1.0, sec_k / 2.0), f"Security/verification keywords present ({int(sec_k)})")

        fin_k = val_map.get("financial_keyword_count", 0.0)
        if fin_k > 0:
            _evaluate_feature("financial_keyword_count", min(1.0, fin_k / 2.0), f"Banking/financial keywords present ({int(fin_k)})")

        urg_k = val_map.get("urgency_keyword_count", 0.0)
        if urg_k > 0:
            _evaluate_feature("urgency_keyword_count", min(1.0, urg_k / 2.0), f"Account urgency/action keywords present ({int(urg_k)})")

        # Structural & lexical indicators (normalized above baseline)
        sub_cnt = val_map.get("subdomain_count", 0.0)
        if sub_cnt >= 2.0:
            _evaluate_feature("subdomain_count", min(1.0, (sub_cnt - 1.0) / 2.0), f"Excessive subdomain nesting depth ({int(sub_cnt)})")

        digit_r = val_map.get("domain_digit_ratio", 0.0)
        if digit_r > 0.10:
            _evaluate_feature("domain_digit_ratio", min(1.0, digit_r / 0.35), f"Elevated numeric digit ratio in domain ({digit_r:.1%})")

        u_ent = val_map.get("url_entropy", 0.0)
        if u_ent > 4.3:
            _evaluate_feature("url_entropy", min(1.0, (u_ent - 4.3) / 1.5), f"Elevated URL Shannon randomness entropy ({u_ent:.2f} bits/char)")

        d_ent = val_map.get("domain_entropy", 0.0)
        if d_ent > 3.8:
            _evaluate_feature("domain_entropy", min(1.0, (d_ent - 3.8) / 1.5), f"High domain randomness entropy ({d_ent:.2f} bits/char)")

        delims = val_map.get("count_delimiters", 0.0)
        if delims > 5.0:
            _evaluate_feature("count_delimiters", min(1.0, (delims - 5.0) / 6.0), f"High special delimiter count ({int(delims)})")

        u_len = val_map.get("url_length", 0.0)
        if u_len > 90.0:
            _evaluate_feature("url_length", min(1.0, (u_len - 90.0) / 110.0), f"Extremely long URL length ({int(u_len)} characters)")

        # Sort top contributing local risk factors descending by impact
        sorted_contributing = dict(
            sorted(contributing.items(), key=lambda item: item[1], reverse=True)[:5]
        )
        evidence_details.sort(key=lambda item: item["local_impact"], reverse=True)

        return sorted_contributing, evidence_details[:5]

    def predict(self, url: str) -> Dict[str, Any]:
        """
        Executes prediction on target URL.
        If a validated trained model is loaded, returns real ML prediction and contributing features.
        If no validated model artifact exists, marks status 'unavailable' without fabricating probabilities.
        """
        # Always extract structural and lexical features honestly
        extracted = URLFeatureExtractor.extract_features(url)
        vector = URLFeatureExtractor.to_feature_vector(extracted)

        # Integrity Check: If model is not trained or invalid, NEVER invent or fake a probability
        if not self.is_trained or self.model_instance is None:
            detail = f" ({self.load_error})" if self.load_error else ""
            return {
                "status": "unavailable",
                "is_trained": False,
                "model": self.model_name,
                "model_version": self.model_version,
                "probability_phish": None,
                "confidence": None,
                "explanation_method": "none",
                "feature_importances": None,
                "contributing_features": None,
                "local_evidence": [],
                "extracted_features": {
                    "url_length": extracted["url_length"],
                    "subdomain_count": extracted["subdomain_count"],
                    "url_entropy": extracted["url_entropy"],
                    "domain_entropy": extracted["domain_entropy"],
                    "is_punycode": extracted["is_punycode"],
                    "has_ip_literal": extracted["has_ip_literal"],
                    "matched_keywords": extracted["matched_keywords"],
                    "squatted_brands": extracted["squatted_brands"],
                    "is_high_risk_tld": extracted["is_high_risk_tld"],
                },
                "message": (
                    f"ML inference is unavailable{detail}: Validated scikit-learn model artifact not loaded. "
                    f"Run 'python -m backend.app.ml.train' to train and calibrate a Random Forest / Gradient Boosting model."
                ),
            }

        # Real ML inference using loaded estimator
        try:
            import numpy as np
            X = np.array([vector])
            probabilities = self.model_instance.predict_proba(X)[0]
            prob_phish = round(float(probabilities[1]), 4)
            confidence = round(float(max(probabilities)), 4)

            # Global feature importances from manifest
            importances = self.metadata.get("feature_importances", {})

            # Calculate defensible local evidence without multiplying raw unscaled values
            sorted_contributing, local_evidence = self.compute_local_evidence(
                extracted=extracted,
                vector=vector,
                global_importances=importances,
            )

            return {
                "status": "operational",
                "is_trained": True,
                "model": self.model_name,
                "model_version": self.model_version,
                "probability_phish": prob_phish,
                "confidence": confidence,
                "explanation_method": "normalized_local_risk_attribution",
                "global_feature_importances": importances,
                "feature_importances": importances,  # Kept for backward compatibility
                "contributing_features": sorted_contributing,
                "local_evidence": local_evidence,
                "extracted_features": {
                    "url_length": extracted["url_length"],
                    "subdomain_count": extracted["subdomain_count"],
                    "url_entropy": extracted["url_entropy"],
                    "domain_entropy": extracted["domain_entropy"],
                    "is_punycode": extracted["is_punycode"],
                    "has_ip_literal": extracted["has_ip_literal"],
                    "matched_keywords": extracted["matched_keywords"],
                    "squatted_brands": extracted["squatted_brands"],
                },
                "message": "Real ML prediction evaluated with calibrated probabilities.",
            }
        except Exception as e:
            return {
                "status": "error",
                "is_trained": False,
                "model": self.model_name,
                "model_version": self.model_version,
                "probability_phish": None,
                "confidence": None,
                "error": str(e),
                "message": f"Inference execution failed: {str(e)}",
            }


